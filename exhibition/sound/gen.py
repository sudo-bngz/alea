    per_line = int(0.86 / cw)
    VX0, VW, VY, VH = 0.07, 0.86, 1.13, 0.11
    L = ["  // ── the voice: its words as said, and its sound going by ──"]
    typed, saying, labs = [], [], []
    for i, (n, _, a, b, e) in enumerate(demo_lines(ep)):
        L.append(f"  let vis{i} = (T >= {a}) * (T < {b})")
