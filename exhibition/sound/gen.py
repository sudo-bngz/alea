#!/usr/bin/env python3
"""alea, one sound at a time — the template of the sound series.

    python3 gen.py s01-beat.json        # writes s01-beat-track.alea, s01-beat.alea, s01-beat-program.alea

An episode is built in two passes:

1. `NN-track.alea` is the music: the layers of the episode's program, each
   coming in on its bar, every event at half intensity while a line is
   spoken (the ducking is written into the events, not run on the mix), and
   the voice. `alea NN-track.alea` gives the WAV; copy it to `NN.wav`.
2. `NN.alea` is the Reel: it opens that WAV, plays it, and its picture
   listens to it (`.bass`, `.mid`, `.treble`) and to the clock of the
   meter (the step grid). The captions follow the spoken words.

`NN-program.alea` is the program on screen, whole and runnable on its own:
what the episode teaches, without the Reel's machinery (the entrances, the
ducking, the narration). Its drums are `steps` patterns, so they sweep from
left to right over the work (a step's `x` is its moment); the track keeps
them in the middle, which is the only other difference.

The look, the opening, the code panel and the captions come from the
picture series' template (`../series/gen.py`).
"""
import importlib.util, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("series_gen", os.path.join(HERE, "..", "series", "gen.py"))
S = importlib.util.module_from_spec(_spec)
_argv, sys.argv = sys.argv, sys.argv[:1]
_spec.loader.exec_module(S)
sys.argv = _argv

ENGINE = "../../voices/kokoro-misaki.py"   # paths resolve from where alea runs: run from sound/
VOICE = "af_kore"
LAY = {"y0": 0.12, "size": 0.036, "dy": 0.065}

# the step grid
GX0, CW = 0.22, 0.045
GY0, RH = 0.70, 0.075


def times(ep):
    bar = 240.0 / ep["tempo"]
    return bar, bar / 16


def euclid16(hits, steps, rotate=0):
    """alea's `euclid` (src/eval.rs) on a bar of sixteen sixteenths: a hit on step k
    when ((k - rotate) * hits) mod steps < hits; 1 on the first of the cycle, 0.8 after."""
    out = [0.0] * 16
    for k in range(steps):
        kk = (k - rotate) % steps
        if (kk * hits) % steps < hits:
            out[k * 16 // steps] = 1.0 if kk == 0 else 0.8
    return out


def hits_of(s):
    if isinstance(s, dict):
        return euclid16(*s["euclid"])
    v = {"X": 1.0, "x": 0.65, "o": 0.35}
    cells = [v.get(c, 0.0) for c in s if not c.isspace()]
    assert len(cells) == 16, s
    return cells


def lines_said(ep):
    """(name, text, at) of every spoken line, in order."""
    bar, _ = times(ep)
    out = [("l0", ep["hook"]["say"], ep["hook"]["bar"] * bar + ep["hook"].get("delay", 0.6))]
    for k, b in enumerate(ep["beats"]):
        out.append((f"l{k + 1}", b["say"], (b["bar"] + 1) * bar + 0.15))
    out.append((f"l{len(ep['beats']) + 1}", ep["end"]["say"], ep["end"]["bar"] * bar + 1.4))
    return out


def say_lines(ep):
    return [f'  let {n} = say("{s}", at: {a:.2f}, engine: ENGINE, voice: VOICE, speed: 1.0, gain: 2.5)' for n, s, a in lines_said(ep)]


# ── pass 1: the track ─────────────────────────────────────────────────────

def track(ep):
    bar, six = times(ep)
    nb = ep["bars"]
    total = nb * bar
    steps_total = nb * 16
    L = [f"// alea, one sound at a time · {ep['number']} — {ep['title']}: the track.",
         f"// Generated by sound/gen.py from sound/{ep['slug']}.json. The layers of",
         f"// {ep['slug']}-program.alea, each coming in on its bar, at half intensity",
         "// while a line is spoken, and the voice. Render it, then copy the WAV to",
         f"// {ep['slug']}.wav for the Reel ({ep['slug']}.alea) to play and listen to.",
         "",
         f"work {ep['work']}Track {{",
         f"  let total = {total:.4f}",
         f"  let SIX = {six:.6f}",
         f'  let ENGINE = "{ENGINE}"',
         f'  let VOICE = "{VOICE}"']
    L += say_lines(ep)
    talks = " + ".join(f"(s >= {n}.start) * (s < {n}.end + 0.25)" for n, _, _ in lines_said(ep))
    L.append(f"  let talk(s) = {talks}")
    L.append("  let duck(s) = 1 - 0.5 * min(1, talk(s))")
    L.append("  let semi(s) = 1 - (s + 0.5) / 36")
    L.append("")
    for ly in ep["layers"]:
        body = " ".join(x.strip() for x in ly["synth"])
        L.append(f"  let {ly['name']} = synth {{ {body} }}")
    L.append("  let tone = synth { (sine() + sine(note.freq * 1.5) * 0.3) * adsr(attack: 0.4, decay: 0.6, sustain: 0.6, release: 2.5) * 0.5 }")
    L.append("")
    layers = []
    for ly in ep["layers"]:
        h = hits_of(ly["hits"])
        lst = "[" + ", ".join(f"{v:g}" for v in h) + "]"
        vel = f"~uniform({ly['chance'][0]}, {ly['chance'][1]})" if "chance" in ly else "1"
        x = "0.5"
        e0 = ly["enter"] * 16
        sw = ly.get("swing")
        spans = [(ly["name"], e0, sw["from"] * 16 if sw else steps_total, None)]
        if sw:
            spans.append((ly["name"] + "_sw", sw["from"] * 16, steps_total, sw["amount"]))
        for pname, a, b, swing in spans:
            L.append(f"  pattern p_{pname} = repeat {steps_total} event(t: i / {steps_total}, x: {x}, y: 0.5, size: 0.02,")
            L.append(f"      intensity: {lst}[i % 16] * {vel} * (i >= {a}) * (i < {b}) * duck(i * SIX))")
            extra = f", tempo: {ep['tempo']}, swing: {swing}" if swing else ""
            layers.append(f"notes(p_{pname}, instrument: {ly['name']}, gain: {ly['gain']}{extra})")
    L.append(f"  pattern p_tone = repeat 2 event(t: [0.3, 2.4][i] / total, y: semi([0, 7][i]), size: 0.15, intensity: [0.5, 0.3][i])")
    layers.append(f'notes(p_tone, instrument: tone, scale: "chromatic", key: {ep["key"]}, gain: 0.2)')
    L.append("")
    L.append("  let music = [")
    L.append("    " + ", ".join(n for n, _, _ in lines_said(ep)) + ",")
    for x in layers:
        L.append(f"    {x},")
    L.append("  ]")
    L.append(f"  render sound(music, duration: total, room: 0.15, echo: 0.1)")
    L.append("}")
    return "\n".join(L)


# ── the program on screen ─────────────────────────────────────────────────

def program(ep):
    return "\n".join(ep["program"])


# ── pass 2: the Reel ──────────────────────────────────────────────────────

def hit_expr(h, var="col"):
    """a field of `var`: the step's value in the pattern, as a sum of tests."""
    terms = [f"({var} == {k}) * {v:g}" for k, v in enumerate(h) if v > 0]
    if len(terms) == 16 and len(set(h)) == 1:
        return f"{h[0]:g}"
    return " + ".join(terms) if terms else "0"


def reel(ep):
    bar, six = times(ep)
    nb = ep["bars"]
    total = nb * bar
    said = lines_said(ep)
    beats = ep["beats"]
    starts = [0.0, ep["hook"]["bar"] * bar] + [b["bar"] * bar for b in beats] + [ep["drop"]["bar"] * bar, ep["end"]["bar"] * bar, total]
    L = [f"// alea, one sound at a time · {ep['number']} — {ep['title']}: the Reel.",
         f"// Generated by sound/gen.py from sound/{ep['slug']}.json. It plays",
         f"// {ep['slug']}.wav (rendered by {ep['slug']}-track.alea) and its picture",
         "// listens to it: the step grid follows the meter, the meters the bands.",
         "",
         f"work {ep['work']} {{",
         f"  let total = {total:.4f}",
         "  let T = t * total",
         f"  let SIX = {six:.6f}",
         f'  let ENGINE = "{ENGINE}"',
         f'  let VOICE = "{VOICE}"',
         "  let win(a, b) = (T >= a) * (T < b)",
         "  let blink = fract(T * 2) < 0.5",
         f"  let adv = {S.ADV}"]
    for k, v in S.LEVELS.items():
        L.append(f"  let {k} = {v} / 9")
    L.append(f'  let song = open("{ep["slug"]}.wav")')
    L.append("")
    L.append("  // ── the voice (in the track; here for the captions' timings) ──")
    L += say_lines(ep)
    L.append("")
    # labels and captions
    labels = [("h_hook", f"sound  ·  {ep['number'].lower()}", starts[1], starts[2])]
    for k, b in enumerate(beats):
        labels.append((f"h_{k}", b["label"], starts[2 + k], starts[3 + k]))
    labels.append(("h_drop", ep["drop"].get("label", "the beat, whole"), starts[-3], starts[-2]))
    for n, s, a, b in labels:
        L.append(f'  let {n} = text("{s}", x: 0.06, y: -0.19, size: 0.032, font: "mono", align: "left") * win({a:.3f}, {b:.3f})')
    L.append(f"  let header = merge({', '.join(n for n, *_ in labels)})")
    ends = [starts[2]] + [starts[3 + k] for k in range(len(beats))] + [total]
    caps = []
    for (n, s, a), e in zip(said, ends):
        L.extend(S.caption(n, n, s, f"{n}.start", f"{e:.3f}"))
        caps.append(f"c_{n}")
    L.append(f"  let captions = merge({', '.join(caps)})")
    L.append("")
    # opening (from the picture series)
    L += [
        "  let wx0 = 0.29", "  let wx1 = 0.71", "  let ww = 0.034",
        "  let wu = (x - 0.5) / (wx1 - wx0) * tau",
        "  let wcurve = 0.5 + 0.075 * sin(wu)",
        "  let wslope = 0.075 * cos(wu) * tau / (wx1 - wx0)",
        "  let wdist = abs(y - wcurve) / sqrt(1 + wslope * wslope)",
        "  let wfoot = x + (y - wcurve) * wslope / (1 + wslope * wslope)",
        "  let drawnto = wx0 + (wx1 - wx0) * clamp((T - 0.3) / 1.0, 0, 1)",
        "  let wband = smoothstep(ww + 0.002, ww - 0.002, wdist) * step(wx0, wfoot) * step(wfoot, min(wx1, drawnto))",
        "  let wcaps = merge(circle(wx0, 0.5, 2 * ww, softness: 0.002) * (T >= 0.3), circle(wx1, 0.5, 2 * ww, softness: 0.002) * (T >= 1.3))",
        "  let wave = merge(wband, wcaps)",
        '  let handle = text("written.in.alea", x: 0.5, y: 0.74, size: 0.036, font: "mono") * (T >= 1.6)',
        "  let ocur = (abs(x - 0.5) < 0.012) * (abs(y - 0.9) < 0.028) * blink * (T >= 1.6)",
        "  let openf = max(wave * INK, max(handle * GREY, ocur * RED))",
        "",
        f'  let hk1 = text("{ep["number"].lower()}  ·  {ep["title"].lower()}", x: 0.5, y: 0.74, size: 0.036, font: "mono") * (T >= {starts[1] + 0.3:.2f})',
        f'  let hk2 = text("alea, one sound at a time", x: 0.5, y: 0.81, size: 0.03, font: "mono") * (T >= {starts[1] + 0.3:.2f})',
        "  let hookf = max(wave * RED, max(hk1 * INK, hk2 * GREY))",
        "",
    ]
    # the step grid
    view = ep.get("view", "grid")
    if view == "wheel":
        CX, CY, R0, DR = 0.5, 0.93, 0.12, 0.05
        rmax = R0 + DR * (len(ep["layers"]) - 1)
        L.append("  // ── the wheel: a ring of sixteen steps per layer, lit on the meter's clock ──")
        L.append("  let step16 = floor(T / SIX)")
        L.append("  let cur = step16 % 16")
        L.append("  let flash = clamp(1 - fract(T / SIX) * 0.6, 0, 1)")
        L.append(f"  let wdx = x - {CX}")
        L.append(f"  let wdy = y - {CY}")
        L.append("  let wr = sqrt(wdx * wdx + wdy * wdy)")
        L.append("  let wa = fract(atan2(wdx, -wdy) / tau)")
        L.append("  let wk = floor(wa * 16 + 0.5) % 16")
        L.append("  let wak = wk / 16 * tau")
        rows, shown_ats = [], []
        for r, ly in enumerate(ep["layers"]):
            R = R0 + r * DR
            h = hits_of(ly["hits"])
            enter = ly["enter"] * bar
            shown = [b["bar"] for b in beats if ly["name"] in b.get("rows", [])]
            shown_at = (min(shown) * bar + 0.3) if shown else enter
            shown_ats.append(shown_at)
            L.append(f"  let dx{r} = x - ({CX} + {R:.3f} * sin(wak))")
            L.append(f"  let dy{r} = y - ({CY} - {R:.3f} * cos(wak))")
            L.append(f"  let in{r} = (dx{r} * dx{r} + dy{r} * dy{r}) < 0.000169")
            L.append(f"  let hit{r} = {hit_expr(h, 'wk')}")
            L.append(f"  let lit{r} = hit{r} * (wk == cur) * flash * (T >= {enter:.3f})")
            L.append(f'  let lab{r} = text("{ly["label"]}", x: 0.06, y: {CY - R:.3f}, size: 0.028, font: "mono", align: "left")')
            L.append(f"  let row{r} = max(in{r} * max(RULE, max((hit{r} > 0) * GREY, max((hit{r} > 0.5) * INK, max((hit{r} > 0.9) * KEY, (lit{r} > 0.3) * RED)))), lab{r} * GREY) * (T >= {shown_at:.3f})")
            rows.append(f"row{r}")
        reach = " + ".join(f"{DR} * (T >= {t:.3f})" for t in shown_ats[1:]) or "0"
        L.append(f"  let reach = {R0 + 0.03} + {reach}")
        L.append(f"  let hand = (abs(fract(wa - cur / 16 + 0.5) - 0.5) * tau * wr < 0.0025) * (wr > 0.06) * (wr < reach)")
        L.append(f"  let grid = max(merge({', '.join(rows)}), hand * GREY)")
        L.append("")
    else:
        L.append("  // ── the step grid: a row per layer, lit on the meter's clock ──")
        L.append("  let step16 = floor(T / SIX)")
        L.append("  let cur = step16 % 16")
        L.append("  let flash = clamp(1 - fract(T / SIX) * 0.6, 0, 1)")
        L.append(f"  let col = floor((x - {GX0}) / {CW})")
        L.append(f"  let incol = (x >= {GX0}) * (x < {GX0 + 16 * CW:.3f}) * (fract((x - {GX0}) / {CW}) > 0.12) * (fract((x - {GX0}) / {CW}) < 0.88)")
        rows = []
        for r, ly in enumerate(ep["layers"]):
            ry = GY0 + r * RH
            h = hits_of(ly["hits"])
            enter = ly["enter"] * bar
            shown = [b["bar"] for b in beats if ly["name"] in b.get("rows", [])]
            shown_at = (min(shown) * bar + 0.3) if shown else enter
            L.append(f"  let in{r} = incol * ((y - {ry:.3f}) / {RH} > 0.15) * ((y - {ry:.3f}) / {RH} < 0.85)")
            L.append(f"  let hit{r} = {hit_expr(h)}")
            L.append(f"  let lit{r} = hit{r} * (col == cur) * flash * (T >= {enter:.3f})")
            L.append(f'  let lab{r} = text("{ly["label"]}", x: 0.07, y: {ry + RH / 2:.3f}, size: 0.03, font: "mono", align: "left")')
            L.append(f"  let row{r} = max(in{r} * max(RULE, max((hit{r} > 0) * GREY, max((hit{r} > 0.5) * INK, max((hit{r} > 0.9) * KEY, (lit{r} > 0.3) * RED)))), lab{r} * GREY) * (T >= {shown_at:.3f})")
            rows.append(f"row{r}")
        L.append(f"  let playhead = (abs(x - ({GX0} + (cur + 0.5) * {CW})) < {CW * 0.35:.4f}) * (abs(y - {GY0 - 0.025:.3f}) < 0.005)")
        L.append(f"  let grid = max(merge({', '.join(rows)}), playhead * RED)")
        L.append("")
    # the beats
    fields = ["openf * win(0, {:.3f})".format(starts[1]), "hookf * win({:.3f}, {:.3f})".format(starts[1], starts[2])]
    for k, b in enumerate(beats):
        a = starts[2 + k]
        L.append(f"  // ── {b['label']} ──")
        L.extend(S.code_block(f"k{k}", b["code"], a + 0.3, **LAY))
        fields.append(f"max(k{k}_code, grid) * win({a:.3f}, {starts[3 + k]:.3f})")
    # the drop
    a = starts[-3]
    L.append("  // ── the drop: the beat whole, the meters listening to the track ──")
    L.extend(S.code_block("kd", ep["drop"]["code"], a + 0.3, **LAY))
    my = ep.get("meters_y", 1.16)
    for j, (band, lv) in enumerate([("bass", "NUM"), ("mid", "FN"), ("treble", "STR")]):
        yy = my + j * ep.get("meters_dy", 0.05)
        L.append(f'  let ml{j} = text("{band}", x: 0.07, y: {yy:.3f}, size: 0.026, font: "mono", align: "left")')
        L.append(f"  let mb{j} = (x >= {GX0}) * (x < {GX0} + 0.72 * clamp(song.{band}, 0, 1)) * (abs(y - {yy:.3f}) < 0.012)")
    L.append("  let meters = max(max(ml0, max(ml1, ml2)) * GREY, max(mb0 * NUM, max(mb1 * FN, mb2 * STR)))")
    fields.append(f"max(kd_code, max(grid, meters)) * win({a:.3f}, {starts[-2]:.3f})")
    # the end
    e = starts[-2]
    endn = said[-1][0]
    L += [
        "  // ── the end ──",
        "  let nsize = 0.2", "  let nadv = 0.5172 * nsize", "  let nx0e = 0.5 - 2.5 * nadv",
        f'  let name2 = text("alea", x: nx0e, y: 0.5, size: nsize, font: "mono", align: "left") * (T >= {e + 0.3:.2f})',
        f"  let ecur = (abs(x - (nx0e + 4.5 * nadv)) < nadv * 0.42) * (abs(y - 0.5) < nsize * 0.4) * blink * (T >= {e + 0.3:.2f})",
        f'  let e1 = text("one sound at a time  ·  {ep["number"].lower()}  ·  {ep["title"].lower()}", x: 0.5, y: 0.64, size: 0.03, font: "mono") * (T >= {e + 0.7:.2f})',
        f'  let e2 = text("alea.bngz.io", x: 0.5, y: 0.75, size: 0.06, font: "mono") * (T >= {e + 1.0:.2f})',
        f'  let e3 = text("next  ·  {ep["end"]["next"]}", x: 0.5, y: 0.88, size: 0.03, font: "mono") * (T >= {endn}.words[2])',
        f'  let e4 = text("open source  ·  github.com/sudo-bngz/alea", x: 0.5, y: 0.96, size: 0.026, font: "mono") * (T >= {e + 1.6:.2f})',
        "  let endf = max(name2 * INK, max(ecur * RED, max(e1 * INK, max(e2 * RED, max(e3 * GREY, e4 * INK)))))",
    ]
    fields.append(f"endf * win({e:.3f}, {total + 1:.3f})")
    L.append("")
    L.append(f"  let drawn = merge({', '.join(fields)})")
    L.append("  let over = merge(header * RED, captions * INK)")
    L.append(f"  let base = paint(max(drawn, over), palette: {S.PAL}, range: [0, 1])")
    L.append("  let look = film(base, amount: 0.03)")
    L.append("")
    trans = ["jump()", "jump()"] + ["jump()", "pixels(0.3, size: 0.04)"] * 4
    L.append("  let reel = timeline([")
    for i in range(len(starts) - 1):
        p0, p1 = starts[i], starts[i + 1]
        tr = trans[i] if i < len(starts) - 2 else "fade(0.8, through: 0)"
        if i == len(starts) - 3:
            tr = "glitch(0.4, amount: 0.7)"
        L.append(f"      scene(look, {p1 - p0:.3f}, from: {p0:.3f} / total, to: {p1:.3f} / total), {tr},")
    L.append("  ], loop: 1)")
    L.append("")
    L.append(f"  render image(reel, width: 1080, height: 1920, at: {ep.get('cover', 0.75)})")
    L.append("  render video(reel, fps: 30, width: 1080, height: 1920, duration: total, sound: [song])")
    L.append("}")
    return "\n".join(L)


def main():
    path = sys.argv[1]
    ep = json.load(open(path))
    base = os.path.join(os.path.dirname(os.path.abspath(path)), ep["slug"])
    open(base + "-track.alea", "w").write(track(ep) + "\n")
    open(base + "-program.alea", "w").write(program(ep) + "\n")
    open(base + ".alea", "w").write(reel(ep) + "\n")


if __name__ == "__main__":
    main()
