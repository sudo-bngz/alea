#!/usr/bin/env python3
"""Writes the Homebrew formula of a release, from its SHA256SUMS.txt.

    python3 packaging/homebrew/formula.py v0.1.0 SHA256SUMS.txt > alea.rb

The formula goes in the tap, github.com/sudo-bngz/homebrew-tap, as
Formula/alea.rb; then `brew install sudo-bngz/tap/alea`. The release workflow
does this by itself when the repository has a HOMEBREW_TAP_TOKEN secret."""
import sys

REPO = "https://github.com/sudo-bngz/alea"


def main(tag, sums_path):
    sums = {}
    for line in open(sums_path):
        parts = line.split()
        if len(parts) == 2:
            sums[parts[1].lstrip("*")] = parts[0]
    version = tag.lstrip("v")

    def asset(name):
        file = f"alea-{tag}-{name}.tar.gz"
        if file not in sums:
            sys.exit(f"{file} is not in {sums_path}")
        return f'url "{REPO}/releases/download/{tag}/{file}"\n      sha256 "{sums[file]}"'

    print(f'''# Generated by packaging/homebrew/formula.py for alea {tag}.
class Alea < Formula
  desc "Non-deterministic language for generative art: every run draws a new edition"
  homepage "https://alea.bngz.io"
  version "{version}"
  license "MIT"

  on_macos do
    {asset("macos").replace(chr(10) + "      ", chr(10) + "    ")}
  end

  on_linux do
    depends_on "alsa-lib" # live MIDI
    on_intel do
      {asset("linux-x86_64")}
    end
    on_arm do
      {asset("linux-arm64")}
    end
  end

  def install
    bin.install "alea"
    pkgshare.install "examples"
  end

  def caveats
    <<~EOS
      The examples are in #{{opt_pkgshare}}/examples. Try:
        alea #{{opt_pkgshare}}/examples/rosace.alea
      Videos and Reels need ffmpeg (brew install ffmpeg).
    EOS
  end

  test do
    system bin/"alea", "--help"
  end
end''')


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
