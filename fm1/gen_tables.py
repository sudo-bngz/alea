#!/usr/bin/env python3
"""Writes alea_vm_tables.h: the tables alea_vm.h reads, for a sample rate.

    python3 fm1/gen_tables.py [44100] > fm1/alea_vm_tables.h
"""
import math, sys

fs = int(sys.argv[1]) if len(sys.argv) > 1 else 44100
print("/* generated by fm1/gen_tables.py for fs = %d: do not edit */" % fs)
print("#define ALEA_TABLES_FS %du" % fs)
# a quarter sine, Q15
sine = [round(math.sin(math.pi / 2 * k / 256) * 32767) for k in range(257)]
print("static const int16_t ALEA_SINE[257] = {" + ",".join(map(str, sine)) + "};")
# exp(-6.9 u), u = 0..1 in 64 steps, Q16
expd = [round(math.exp(-6.9 * k / 64) * 65536) for k in range(65)]
print("static const int32_t ALEA_EXPD[65] = {" + ",".join(map(str, expd)) + "};")
# tanh(x), x = 0..8 in 128 steps, Q15
tanh = [round(math.tanh(8 * k / 128) * 32767) for k in range(129)]
print("static const int16_t ALEA_TANH[129] = {" + ",".join(map(str, tanh)) + "};")
# the filter's g = tan(pi f / fs), f = 10 Hz * 2^(k/16), k = 0..192 (12 octaves), Q16; above 0.45 fs the top value
top = 0.45 * fs
g = []
for k in range(193):
    f = min(10 * 2 ** (k / 16), top)
    g.append(round(math.tan(math.pi * f / fs) * 65536))
print("static const int32_t ALEA_G[193] = {" + ",".join(map(str, g)) + "};")
print("#define ALEA_G_TOP (%d)" % (int(top) << 16))
# the DC blocker's pole, 1 - 2 pi 15 / fs, Q32
print("#define ALEA_DC_R ((int64_t)%dll)" % round((1 - 2 * math.pi * 15 / fs) * 2 ** 32))
